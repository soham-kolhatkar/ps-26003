const slug = (folder) =>
  folder
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '');

function urlFor({ folder, medium }) {
  const file = folder.toLowerCase().replace(/ /g, '_');
  const path = medium ? `${folder}/Medium/3D/${file}_3d_medium.png` : `${folder}/3D/${file}_3d.png`;
  return `${RAW}/${path.split('/').map(encodeURIComponent).join('/')}`;
}

mkdirSync(OUT, { recursive: true });
const lines = [];
const seen = new Map();
for (const [glyph, spec] of Object.entries(PICTURES)) {
  const entry = typeof spec === 'string' ? { folder: spec } : spec;
  const name = slug(entry.folder);
  if (!seen.has(name)) {
    const file = join(OUT, `${name}.png`);
    if (!existsSync(file)) {
      const res = await fetch(urlFor(entry));
      if (!res.ok) throw new Error(`${glyph} ${entry.folder}: HTTP ${res.status}`);
      writeFileSync(file, Buffer.from(await res.arrayBuffer()));
      console.log(`  ↓ ${name}.png`);
    }
    seen.set(name, true);
  }
  lines.push(`  '${glyph}': require('../../assets/pictures/${name}.png'),`);
}

writeFileSync(
  'src/components/pictureAssets.ts',
  `// GENERATED by scripts/fluent-pictures.mjs. Do not edit; add glyphs there and run it again.
// Pictures: Microsoft Fluent Emoji 3D, MIT licence (assets/pictures/LICENSE).
export const PICTURE_ASSETS: Record<string, number> = {
${lines.join('\n')}
};
`,
);
